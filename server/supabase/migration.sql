-- 1) Kullanicilar
create table if not exists public.users (
  id          bigint generated by default as identity primary key,
  username    text unique not null,
  password    text not null,
  points      integer not null default 0,
  created_at  timestamptz not null default now()
);

-- Eski kurulumda points kolonu yoksa ekle
alter table public.users add column if not exists points integer not null default 0;
alter table public.users add column if not exists created_at timestamptz not null default now();

create index if not exists users_username_idx on public.users (lower(username));

-- 2) Skorlar (mac bazli kayitlar)
create table if not exists public.scores (
  id          bigint generated by default as identity primary key,
  user_id     bigint references public.users(id) on delete cascade,
  score       integer not null,
  song_name   text,
  created_at  timestamptz not null default now()
);

create index if not exists scores_user_idx on public.scores (user_id);
create index if not exists scores_score_idx on public.scores (score desc);

-- 3) Mac kayitlari (ayni mac iki kez puan yazmasin)
create table if not exists public.matches (
  id          bigint generated by default as identity primary key,
  match_id    text unique not null,
  user_id     bigint references public.users(id) on delete cascade,
  points      integer not null default 0,
  created_at  timestamptz not null default now()
);

create index if not exists matches_user_idx on public.matches (user_id);

-- 4) Yonetim islem gecmisi
create table if not exists public.admin_logs (
  id               bigint generated by default as identity primary key,
  action           text not null,
  target_user_id   bigint,
  target_username  text,
  amount           integer,
  reason           text,
  admin_ip         text,
  created_at       timestamptz not null default now()
);

create index if not exists admin_logs_created_idx on public.admin_logs (created_at desc);

-- ------------------------------------------------------------
-- NOT: Servis, SERVICE_ROLE anahtari ile baglanir; bu anahtar
-- RLS'i atlar. Tablolari public API'ye acmayin.
-- anon/authenticated rolleri icin RLS'i acik birakip policy
-- tanimlamamak en guvenlisidir.
-- ------------------------------------------------------------
alter table public.users       enable row level security;
alter table public.scores      enable row level security;
alter table public.matches     enable row level security;
alter table public.admin_logs  enable row level security;
