-- ============================================================
-- dark-engine-service · Supabase semasi
-- Supabase > SQL Editor icinde bir kez calistir.
-- ============================================================

-- 1) Kullanicilar
create table if not exists public.users (
  id          bigint generated by default as identity primary key,
  username    text unique not null,
  password    text not null,
  points      integer not null default 0,
  created_at  timestamptz not null default now()
);

-- Eski kurulumda points kolonu yoksa ekle
alter table public.users add column if not exists points integer not null default 0;
alter table public.users add column if not exists created_at timestamptz not null default now();

create index if not exists users_username_idx on public.users (lower(username));

-- 2) Skorlar (mac bazli kayitlar)
create table if not exists public.scores (
  id          bigint generated by default as identity primary key,
  user_id     bigint references public.users(id) on delete cascade,
  score       integer not null,
  song_name   text,
  created_at  timestamptz not null default now()
);

create index if not exists scores_user_idx on public.scores (user_id);
create index if not exists scores_score_idx on public.scores (score desc);

-- 3) Mac kayitlari (ayni mac iki kez puan yazmasin)
create table if not exists public.matches (
  id          bigint generated by default as identity primary key,
  match_id    text unique not null,
  user_id     bigint references public.users(id) on delete cascade,
  points      integer not null default 0,
  created_at  timestamptz not null default now()
);

create index if not exists matches_user_idx on public.matches (user_id);

-- 4) Yonetim islem gecmisi
create table if not exists public.admin_logs (
  id               bigint generated by default as identity primary key,
  action           text not null,
  target_user_id   bigint,
  target_username  text,
  amount           integer,
  reason           text,
  admin_ip         text,
  created_at       timestamptz not null default now()
);

create index if not exists admin_logs_created_idx on public.admin_logs (created_at desc);

-- ------------------------------------------------------------
-- NOT: Servis, SERVICE_ROLE anahtari ile baglanir; bu anahtar
-- RLS'i atlar. Tablolari public API'ye acmayin.
-- anon/authenticated rolleri icin RLS'i acik birakip policy
-- tanimlamamak en guvenlisidir.
-- ------------------------------------------------------------
alter table public.users       enable row level security;
alter table public.scores      enable row level security;
alter table public.matches     enable row level security;
alter table public.admin_logs  enable row level security;

-- ============================================================
-- 5) MAC KAYITLARI (oyunun dogrudan anon key ile yazdigi tablo)
-- ============================================================
-- Oyun, mac sonunda kaydi Supabase'e kendisi POST eder
-- (mods/supabase.json -> table: match_records). Tablo yoksa istek 404
-- (PGRST205) doner ve ekranda "HATA Http Error #404" gorunur.

create table if not exists public.match_records (
  id            bigint generated by default as identity primary key,
  match_id      text unique not null,
  username      text,
  user_id       bigint,
  song          text,
  difficulty    text,
  score         integer,
  max_combo     integer,
  misses        integer,
  accuracy      numeric,
  points        integer,
  botplay       boolean default false,
  infinite_mode boolean default false,
  practice_mode boolean default false,
  story_mode    boolean default false,
  played_at     text,
  created_at    timestamptz default now()
);

-- Eski kurulumda eksik kolon varsa ekle
alter table public.match_records add column if not exists username      text;
alter table public.match_records add column if not exists user_id       bigint;
alter table public.match_records add column if not exists song          text;
alter table public.match_records add column if not exists difficulty    text;
alter table public.match_records add column if not exists score         integer;
alter table public.match_records add column if not exists max_combo     integer;
alter table public.match_records add column if not exists misses        integer;
alter table public.match_records add column if not exists accuracy      numeric;
alter table public.match_records add column if not exists points        integer;
alter table public.match_records add column if not exists botplay       boolean default false;
alter table public.match_records add column if not exists infinite_mode boolean default false;
alter table public.match_records add column if not exists practice_mode boolean default false;
alter table public.match_records add column if not exists story_mode    boolean default false;
alter table public.match_records add column if not exists played_at     text;

create index if not exists match_records_user_idx on public.match_records (user_id);
create index if not exists match_records_created_idx on public.match_records (created_at desc);

alter table public.match_records enable row level security;

-- Oyun istemcisi anon key ile yazar. Upsert (on_conflict=match_id,
-- resolution=merge-duplicates) kullandigi icin INSERT + UPDATE gerekir.
drop policy if exists "anon can insert matches" on public.match_records;
create policy "anon can insert matches"
  on public.match_records for insert to anon with check (true);

drop policy if exists "anon can update matches" on public.match_records;
create policy "anon can update matches"
  on public.match_records for update to anon using (true) with check (true);

drop policy if exists "anon can read matches" on public.match_records;
create policy "anon can read matches"
  on public.match_records for select to anon using (true);
