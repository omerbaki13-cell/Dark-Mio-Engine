-- 1) Mac kayitlari (oyunun dogrudan anon key ile yazdigi tablo)
create table if not exists public.match_records (id bigint generated by default as identity primary key, match_id text unique not null, username text, user_id bigint, song text, difficulty text, score integer, max_combo integer, misses integer, accuracy numeric, points integer, botplay boolean default false, infinite_mode boolean default false, practice_mode boolean default false, story_mode boolean default false, played_at text, created_at timestamptz default now());

alter table public.match_records enable row level security;

drop policy if exists "anon can insert matches" on public.match_records;

create policy "anon can insert matches" on public.match_records for insert to anon with check (true);

drop policy if exists "anon can update matches" on public.match_records;

create policy "anon can update matches" on public.match_records for update to anon using (true) with check (true);

drop policy if exists "anon can read matches" on public.match_records;

create policy "anon can read matches" on public.match_records for select to anon using (true);

-- 2) Sunucunun ayni maci iki kez puanlamasini engelleyen tablo
create table if not exists public.matches (id bigint generated by default as identity primary key, match_id text unique not null, user_id bigint, points integer not null default 0, created_at timestamptz not null default now());

create index if not exists matches_user_idx on public.matches (user_id);

alter table public.matches enable row level security;

-- 3) Yonetim islem gecmisi
create table if not exists public.admin_logs (id bigint generated by default as identity primary key, action text not null, target_user_id bigint, target_username text, amount integer, reason text, admin_ip text, created_at timestamptz not null default now());

create index if not exists admin_logs_created_idx on public.admin_logs (created_at desc);

alter table public.admin_logs enable row level security;

-- 4) Skorlar (varsa dokunmaz, yoksa olusturur)
create table if not exists public.scores (id bigint generated by default as identity primary key, user_id bigint, score integer not null, song_name text, created_at timestamptz not null default now());

create index if not exists scores_user_idx on public.scores (user_id);

alter table public.scores enable row level security;

-- 5) Kontrol: asagidaki sorgu 4 tablo donmeli
select table_name from information_schema.tables where table_schema = 'public' order by table_name;
